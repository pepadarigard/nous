import { writeFileSync } from 'node:fs'

const out = []
let n = 0
const add = (subjectId, taskNo, topic, text, answer) => {
  out.push({ id: 'seed_' + (++n), subjectId, taskNo, topic, text, answer: String(answer) })
}

// Детерминированный генератор: банк должен быть одинаковым при каждой пересборке.
let seed = 20270528
const rnd = () => ((seed = (seed * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff)
const pick = (a) => a[Math.floor(rnd() * a.length)]
const int = (a, b) => a + Math.floor(rnd() * (b - a + 1))

// ---------- Математика (профиль) ----------

// № 1. Площадь треугольника и трапеции по формуле.
for (let i = 0; i < 6; i++) {
  const a = int(4, 20), h = int(3, 16)
  const s = (a * h) / 2
  if (!Number.isInteger(s)) { i--; continue }
  add('math_prof', 1, 'Планиметрия',
    `Основание треугольника равно ${a}, а высота, проведённая к нему, равна ${h}. Найдите площадь треугольника.`, s)
}
for (let i = 0; i < 4; i++) {
  const a = int(3, 14), b = int(a + 1, 22), h = int(2, 12)
  const s = ((a + b) / 2) * h
  if (!Number.isInteger(s)) { i--; continue }
  add('math_prof', 1, 'Планиметрия',
    `Основания трапеции равны ${a} и ${b}, высота равна ${h}. Найдите площадь трапеции.`, s)
}

// № 4. Классическая вероятность — «прослужит больше года» и жребий.
for (let i = 0; i < 5; i++) {
  const p1 = int(88, 97) / 100, p2 = (Math.round(p1 * 100) - int(4, 12)) / 100
  const ans = Math.round((p1 - p2) * 100) / 100
  add('math_prof', 4, 'Вероятность',
    `Вероятность того, что новый чайник прослужит больше года, равна ${String(p1).replace('.', ',')}. ` +
    `Вероятность того, что он прослужит больше двух лет, равна ${String(p2).replace('.', ',')}. ` +
    `Найдите вероятность того, что чайник прослужит меньше двух лет, но больше года.`, String(ans).replace('.', ','))
}
for (let i = 0; i < 5; i++) {
  const total = pick([20, 25, 40, 50]), good = int(3, total / 2)
  const ans = good / total
  if (Math.round(ans * 1000) / 1000 !== ans) { i--; continue }
  add('math_prof', 4, 'Вероятность',
    `В соревновании участвуют ${total} спортсменов, из них ${good} — из России. ` +
    `Порядок выступления определяется жребием. Найдите вероятность того, что первым будет выступать спортсмен из России.`,
    String(ans).replace('.', ','))
}

// № 6. Простейшие уравнения — корень целый по построению.
for (let i = 0; i < 5; i++) {
  const base = pick([2, 3, 4, 5]), k = int(2, 4), a = int(1, 9)
  add('math_prof', 6, 'Уравнения',
    `Найдите корень уравнения ${base}^(x − ${a}) = ${base ** k}.`, a + k)
}
for (let i = 0; i < 5; i++) {
  const base = pick([2, 3, 5]), c = int(2, 4), b = int(1, 20)
  add('math_prof', 6, 'Уравнения',
    `Найдите корень уравнения log_${base}(x + ${b}) = ${c}.`, base ** c - b)
}
for (let i = 0; i < 4; i++) {
  const b = int(3, 12), a = int(1, 30)
  add('math_prof', 6, 'Уравнения',
    `Найдите корень уравнения √(x + ${a}) = ${b}.`, b * b - a)
}

// № 7. Вычисления: логарифмы и степени с целым результатом.
for (let i = 0; i < 5; i++) {
  const base = pick([2, 3, 5, 7]), m = int(2, 5), k = int(1, 4)
  add('math_prof', 7, 'Вычисления',
    `Найдите значение выражения log_${base}(${base ** m}) · ${k}.`, m * k)
}
for (let i = 0; i < 5; i++) {
  const a = pick([2, 3, 5]), m = int(5, 9), k = int(1, 4)
  add('math_prof', 7, 'Вычисления',
    `Найдите значение выражения ${a}^${m} / ${a}^${m - k}.`, a ** k)
}

// ---------- Информатика ----------

// № 7. Объём файла: изображение и звук.
for (let i = 0; i < 5; i++) {
  const w = pick([640, 800, 1024, 1280]), h = pick([480, 600, 768, 1024]), depth = pick([8, 16, 24, 32])
  const kb = (w * h * depth) / 8 / 1024
  if (!Number.isInteger(kb)) { i--; continue }
  add('informatics', 7, 'Объём данных',
    `Несжатое растровое изображение размером ${w} × ${h} пикселей сохранили с глубиной цвета ${depth} бит на пиксель. ` +
    `Определите размер файла в Кбайт (служебные данные не учитывать).`, kb)
}
for (let i = 0; i < 4; i++) {
  const freq = pick([16000, 24000, 32000, 48000]), bits = pick([8, 16]), sec = pick([10, 15, 30, 60]), ch = pick([1, 2])
  const kb = (freq * bits * sec * ch) / 8 / 1024
  if (!Number.isInteger(kb)) { i--; continue }
  add('informatics', 7, 'Объём данных',
    `Производится ${ch === 1 ? 'одноканальная (моно)' : 'двухканальная (стерео)'} звукозапись с частотой дискретизации ${freq} Гц ` +
    `и разрешением ${bits} бит. Запись длится ${sec} секунд. Определите размер файла в Кбайт (сжатие не используется).`, kb)
}

// № 8. Комбинаторика слов — считаем перебором.
for (let i = 0; i < 5; i++) {
  const letters = pick([['А', 'Б', 'В'], ['К', 'Л', 'М', 'Н'], ['А', 'О', 'У', 'Ы', 'Э']])
  const len = int(3, 4)
  const vowels = new Set(['А', 'О', 'У', 'Ы', 'Э'])
  let count = 0
  const walk = (word) => {
    if (word.length === len) { if (!vowels.has(word[0])) count++; return }
    for (const c of letters) walk(word + c)
  }
  walk('')
  if (count === 0) { i--; continue }
  add('informatics', 8, 'Комбинаторика',
    `Все ${len}-буквенные слова составляются из букв ${letters.join(', ')}. Буквы могут повторяться. ` +
    `Сколько существует слов, которые НЕ начинаются с гласной буквы?`, count)
}

// № 11. Память под идентификаторы: округление вверх дважды.
for (let i = 0; i < 5; i++) {
  const alphabet = pick([26, 30, 33, 60, 68]), len = int(6, 12), people = pick([20, 50, 100, 200])
  const bitsPerChar = Math.ceil(Math.log2(alphabet))
  const bytes = Math.ceil((bitsPerChar * len) / 8)
  add('informatics', 11, 'Кодирование',
    `Для регистрации на сайте каждому пользователю выдаётся идентификатор из ровно ${len} символов. ` +
    `В качестве символов используют ${alphabet} различных знаков. Каждый такой идентификатор в компьютерной программе ` +
    `записывается минимально возможным и одинаковым целым количеством байт, при этом используется посимвольное кодирование ` +
    `и все символы кодируются одинаковым и минимально возможным количеством бит. ` +
    `Определите объём памяти в байтах, отводимый программой для записи ${people} идентификаторов.`, bytes * people)
}

// № 14. Системы счисления — перевод и подсчёт единиц.
for (let i = 0; i < 5; i++) {
  const base = pick([2, 3, 5, 8, 16])
  const value = int(50, 500)
  add('informatics', 14, 'Системы счисления',
    `Число ${value} записали в системе счисления с основанием ${base}. Сколько значащих цифр в этой записи?`,
    value.toString(base).length)
}
for (let i = 0; i < 4; i++) {
  const value = int(100, 4000)
  add('informatics', 14, 'Системы счисления',
    `Сколько единиц содержится в двоичной записи числа ${value}?`,
    value.toString(2).split('').filter((c) => c === '1').length)
}

// № 25. Делители.
for (let i = 0; i < 4; i++) {
  const value = pick([360, 480, 600, 720, 840, 900])
  let count = 0
  for (let d = 1; d <= value; d++) if (value % d === 0) count++
  add('informatics', 25, 'Делители',
    `Сколько всего натуральных делителей у числа ${value}?`, count)
}

// ---------- Русский язык ----------
// Здесь ответ не вычисляется, поэтому берём только то, в чём нет сомнений:
// слова из орфоэпического минимума с однозначным, широко известным ударением.

const stress = [
  ['звонИт', 'звОнит'], ['тОрты', 'тортЫ'], ['бАнты', 'бантЫ'], ['красИвее', 'красивЕе'],
  ['договОр', 'дОговор'], ['каталОг', 'катАлог'], ['свЁкла', 'свеклА'], ['щавЕль', 'щАвель'],
  ['жалюзИ', 'жАлюзи'], ['квартАл', 'квАртал'], ['тУфля', 'туфлЯ'], ['слИвовый', 'сливОвый'],
  ['облегчИть', 'облЕгчить'], ['цепОчка', 'цЕпочка'], ['граждАнство', 'грАжданство'],
]
for (const [right, wrong] of stress) {
  const others = stress.filter((p) => p[0] !== right).slice(0, 4).map((p) => p[0])
  add('russian', 4, 'Ударение',
    `В одном из приведённых ниже слов допущена ошибка в постановке ударения: НЕВЕРНО выделена буква, ` +
    `обозначающая ударный гласный звук. Выпишите это слово правильно.\n\n${[wrong, ...others].join('   ')}`,
    right.toLowerCase())
}

// ---------- вывод ----------

const body = out
  .map((q) => {
    const esc = (s) => JSON.stringify(s)
    return `  { id: ${esc(q.id)}, subjectId: ${esc(q.subjectId)}, taskNo: ${q.taskNo}, topic: ${esc(q.topic)}, text: ${esc(q.text)}, answer: ${esc(q.answer)} },`
  })
  .join('\n')

