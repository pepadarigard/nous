export function generateOne(subjectId: string, taskNo: number, rnd: Rnd = Math.random): GeneratedTask | null {
  const spec = REGISTRY[subjectId]?.[taskNo]
  if (!spec) return null
  const made = pick(rnd, spec.families)(rnd)
  if (!made) return null
  return { subjectId, taskNo, topic: spec.topic, ...made }
}

/**
 * Набор заданий для банка. Дубли по тексту отсеиваются: одинаковые числа иногда
 * выпадают дважды, и получать в подходе два одинаковых задания неприятно.
 */
export function generateTasks(
  subjectId: string,
  taskNo: number,
  count: number,
  rnd: Rnd = Math.random,
): Question[] {
  const seen = new Set<string>()
  const out: Question[] = []
  // Потолок попыток: у некоторых номеров пространство вариантов невелико,
  // и без него цикл крутился бы вечно, пытаясь набрать недостижимое число.
  for (let tries = 0; tries < count * 40 && out.length < count; tries++) {
    const t = generateOne(subjectId, taskNo, rnd)
    if (!t || seen.has(t.text)) continue
    seen.add(t.text)
    out.push({
      id: uid('q_'),
      subjectId: t.subjectId,
      taskNo: t.taskNo,
      topic: t.topic,
      text: t.text,
      answer: t.answer,
      solution: t.solution,
      origin: 'import',
      createdAt: new Date().toISOString(),
    })
  }
  return out
}

/** Стартовый набор: по нескольку заданий на каждый доступный номер предмета. */
export function generateStarterSet(subjectIds: string[], perNumber = 6, rnd: Rnd = Math.random): Question[] {
  const out: Question[] = []
  for (const sid of subjectIds) {
    for (const no of generatedNumbers(sid)) out.push(...generateTasks(sid, no, perNumber, rnd))
  }
  return out
}
