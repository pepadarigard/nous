/** Справочники по выбранным предметам плюс общие. */
export function referenceFor(subjectIds: string[]): ReferenceDoc[] {
  return REFERENCE.filter((d) => !d.subjectId || subjectIds.includes(d.subjectId))
}

/** Поиск по содержимому справочников — для общего поиска в «Материалах». */
export function searchReference(query: string): { doc: ReferenceDoc; line: string }[] {
  const q = query.trim().toLowerCase()
  if (q.length < 2) return []
  const out: { doc: ReferenceDoc; line: string }[] = []
  for (const doc of REFERENCE) {
    for (const s of doc.sections) {
      for (const line of s.lines) {
        if (line.toLowerCase().includes(q)) out.push({ doc, line })
      }
    }
  }
  return out.slice(0, 40)
}
