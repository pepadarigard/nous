// Встроенные справочники — то, во что заглядывают каждый день.
//
// Почему они здесь, а не в разделе «Материалы» как файлы: раздел материалов —
// для СВОИХ файлов ученика, и из коробки он пуст. А формулы и ударения нужны с
// первого дня, без интернета и без того, чтобы их где-то доставать.
//
// Что можно зашивать, а что нельзя. Ударение в слове, формула площади и шкала
// перевода баллов — это ФАКТЫ, они ничьи. Готовые сборники задач — чужая
// компиляция, их в сборку не кладём (см. seedBank.ts).
//
// Списки составлены своими руками по нормам литературного языка и школьному
// курсу. Официальный орфоэпический словник ФИПИ на 2027 год к моменту сборки
// ещё не опубликован — когда выйдет, список стоит сверить с ним.

