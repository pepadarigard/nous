// Краткая теория по номерам заданий ЕГЭ.
//
// Зачем. Занятие «Теория: Паронимы» говорило «разбери тему и выпиши правило» —
// то есть приложение знало тему, но по ней у него не было ни слова. Теперь есть:
// правило, порядок действий и типовые ловушки прямо в занятии, офлайн и без ИИ.
//
// Это НЕ учебник и не замена ему. Это шпаргалка: то, что реально решает задание,
// без истории вопроса и без исключений третьего порядка. Всё написано своими
// словами — чужие тексты в приложение не кладём.

export interface TaskTheory {
  /** Что от тебя требуется — одна-две фразы. */
  rule: string
  /** Порядок действий: как решать это задание руками. */
  steps?: string[]
  /** На чём чаще всего теряют балл. */
  traps?: string[]
  /** Что придётся выучить: без этого задание не берётся. */
  learn?: string
}

export type SubjectTheory = Record<number, TaskTheory>
