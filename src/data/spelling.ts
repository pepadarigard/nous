/**
 * Сверка наших букв с ответами ФИПИ.
 *
 * Берём ряды из официальной демоверсии, подставляем букву КАЖДОМУ слову по
 * нашим спискам и решаем задание так, как решал бы ученик: ряд идёт в ответ,
 * если буква во всех его словах одна. Полученный ответ должен совпасть с
 * официальным. Если у какого-то слова у нас записана не та буква — не совпадёт.
 *
 * Возвращает список расхождений; пустой список значит, что данные согласны
 * с опубликованными ответами. Слова, которых у нас пока нет, не считаются
 * ошибкой — про них честно сообщается отдельной строкой.
 */
export function checkAgainstDemo(): string[] {
  const letter = new Map<string, string>()
  for (const [w, l] of [...PREFIX_WORDS, ...SUFFIX_WORDS, ...ENDING_WORDS]) letter.set(w, l)
  for (const [w, l] of ROOT_WORDS) letter.set(w, l)

  const problems: string[] = []
  for (const task of RU_DEMO_2027) {
    const missing: string[] = []
    const got = task.rows
      .map((row, i) => {
        const letters = row.map((w) => letter.get(w))
        for (let k = 0; k < row.length; k++) if (letters[k] === undefined) missing.push(row[k])
        if (letters.some((x) => x === undefined)) return 0
        return new Set(letters).size === 1 ? i + 1 : 0
      })
      .filter(Boolean)
      .join('')
    if (missing.length) {
      problems.push(`№${task.no}: нет в списках — ${missing.join(', ')}`)
    } else if (got !== task.answer) {
      problems.push(`№${task.no}: по нашим данным ответ ${got || '(пусто)'}, у ФИПИ ${task.answer}`)
    }
  }
  return problems
}
