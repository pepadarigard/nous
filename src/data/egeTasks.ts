/** Есть ли готовая структура для предмета (иначе офлайн-план не собрать). */
export function hasTaskMap(subjectId: string): boolean {
  return !!EGE_TASKS[subjectId]?.length
}

export const OFFLINE_SUBJECTS = Object.keys(EGE_TASKS)

/** Описание номера задания целиком. */
export function taskInfo(subjectId: string, taskNo?: number): EgeTask | undefined {
  if (taskNo === undefined) return undefined
  return EGE_TASKS[subjectId]?.find((t) => t.no === taskNo)
}

/** Раздел курса, к которому относится номер. Пусто — номера нет в структуре. */
export function taskSection(subjectId: string, taskNo?: number): string {
  return taskInfo(subjectId, taskNo)?.section ?? ''
}

/** Разделы предмета по порядку появления в работе, с номерами каждого. */
export function sectionsOf(subjectId: string): { section: string; tasks: number[] }[] {
  const out: { section: string; tasks: number[] }[] = []
  for (const t of EGE_TASKS[subjectId] ?? []) {
    const found = out.find((s) => s.section === t.section)
    if (found) found.tasks.push(t.no)
    else out.push({ section: t.section, tasks: [t.no] })
  }
  return out
}

/**
 * Задание второй части: развёрнутый ответ, а не строка в бланк.
 *
 * Для приложения это принципиально другой режим. Такие задания решают на листе,
 * ответ оценивается по критериям, а не сверяется с эталоном, и поле в клеточку
 * им не подходит: у задачи с параметром «ответ» — это несколько страниц выкладок.
 */
export function isPart2(subjectId: string, taskNo?: number): boolean {
  return Boolean(taskInfo(subjectId, taskNo)?.part2)
}

/** Как назвать вторую часть у этого предмета — сочинение это или развёрнутый ответ. */
export function part2Label(subjectId: string, taskNo?: number): string {
  if (!isPart2(subjectId, taskNo)) return ''
  if (subjectId === 'russian') return 'сочинение'
  return 'вторая часть'
}
