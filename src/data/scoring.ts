export interface SubjectScoring {
  /** Максимальный первичный балл за всю работу. */
  maxPrimary: number
  /** № задания → первичные баллы за него. */
  points: Record<number, number>
  /** Шкала: индекс — первичный балл, значение — тестовый (0–100). */
  toTest: number[]
  /** Год структуры КИМ, из которой взяты веса. */
  structureYear: number
  /** Год шкалы перевода. */
  scaleYear: number
  /** Порог для поступления в вуз (тестовые баллы). */
  minTest: number
  /** Сколько длится настоящий экзамен, минут (для пробника). */
  minutes: number
}

/** Развернуть «диапазон номеров → балл» в карту. */
function pts(...groups: [number[], number][]): Record<number, number> {
  const out: Record<number, number> = {}
  for (const [nos, p] of groups) for (const no of nos) out[no] = p
  return out
}

/** Номера от a до b включительно. */
function range(a: number, b: number): number[] {
  return Array.from({ length: b - a + 1 }, (_, i) => a + i)
}

