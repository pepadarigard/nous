/** Есть ли для предмета официальные веса и шкала. */
export function hasScoring(subjectId: string): boolean {
  return subjectId in SCORING
}

/** Первичных баллов за задание (0, если такого номера в работе нет). */
export function taskPoints(subjectId: string, taskNo: number): number {
  return SCORING[subjectId]?.points[taskNo] ?? 0
}

/**
 * Первичный балл → тестовый. Дробный первичный округляем вниз: обещать балл,
 * который ещё не набран, — то же враньё, только вежливое.
 */
export function toTestScore(subjectId: string, primary: number): number {
  const s = SCORING[subjectId]
  if (!s) return 0
  const i = Math.max(0, Math.min(s.toTest.length - 1, Math.floor(primary)))
  return s.toTest[i]
}

/**
 * Сходятся ли данные сами с собой: сумма весов равна заявленному максимуму,
 * шкала покрывает все первичные баллы и не убывает. Гоняется тестом, а не в проде.
 */
export function checkScoring(): string[] {
  const problems: string[] = []
  for (const [id, s] of Object.entries(SCORING)) {
    const sum = Object.values(s.points).reduce((a, b) => a + b, 0)
    if (sum !== s.maxPrimary) problems.push(`${id}: сумма весов ${sum} ≠ максимума ${s.maxPrimary}`)
    if (s.toTest[0] !== 0) problems.push(`${id}: шкала начинается не с нуля`)
    if (s.toTest[s.toTest.length - 1] !== 100) problems.push(`${id}: шкала кончается не на 100`)
    for (let i = 1; i < s.toTest.length; i++) {
      if (s.toTest[i] < s.toTest[i - 1]) {
        problems.push(`${id}: шкала убывает на ${i} (${s.toTest[i - 1]} → ${s.toTest[i]})`)
      }
    }
    // Шкала короче максимума — это не опечатка, а известное расхождение (см. шапку файла).
    if (s.toTest.length < s.maxPrimary + 1) {
      problems.push(`${id}: ШКАЛА УСТАРЕЛА — рассчитана на ${s.toTest.length - 1}, а максимум ${s.maxPrimary}`)
    }
  }
  return problems
}
